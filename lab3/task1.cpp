#include <iostream>  // Библиотека для ввода-вывода (cin, cout)
#include <iomanip>   // Библиотека для форматирования вывода (setw, setprecision)

using namespace std; // Чтобы не писать std:: перед cin, cout

// Функция, заданная графически (вариант 15)
// По графику определены 5 участков
double func(double x) {
    // Участок 1: x <= -5 -> y = 0 (горизонтальная линия)
    if (x <= -5) return 0;
    
    // Участок 2: -5 < x <= 0 -> y = 2x + 10 (прямая вверх)
    if (x <= 0) return 2 * x + 10;
    
    // Участок 3: 0 < x <= 5 -> y = -2x + 10 (прямая вниз)
    if (x <= 5) return -2 * x + 10;
    
    // Участок 4: 5 < x <= 8 -> y = 2x - 10 (прямая вверх)
    if (x <= 8) return 2 * x - 10;
    
    // Участок 5: x > 8 -> y = 6 (горизонтальная линия)
    return 6;
}

// Главная функция программы
int main() {
    double xn, xk, dx;  // xn - начало, xk - конец, dx - шаг
    
    // Ввод данных с клавиатуры
    cout << "Xnach: "; cin >> xn;   // Вводим начало интервала
    cout << "Xkon: "; cin >> xk;    // Вводим конец интервала
    cout << "dx: "; cin >> dx;      // Вводим шаг
    
    // Настройка вывода: фиксированный формат с 2 знаками после запятой
    cout << fixed << setprecision(2);
    
    // Вывод шапки таблицы
    cout << "\n-----------------------------\n";
    cout << "|     x     |     y     |\n";
    cout << "-----------------------------\n";
    
    // Циклический вычислительный процесс
    // Перебираем x от xn до xk с шагом dx
    // 1e-9 добавляем для устранения погрешности double
    for (double x = xn; x <= xk + 1e-9; x += dx) {
        // setw(8) - ширина поля 8 символов для ровной таблицы
        // func(x) - вычисляем значение y для текущего x
        cout << "| " << setw(8) << x << " | " << setw(8) << func(x) << " |\n";
    }
    
    // Нижняя граница таблицы
    cout << "-----------------------------\n";
    
    return 0;  // Успешное завершение программы
}
